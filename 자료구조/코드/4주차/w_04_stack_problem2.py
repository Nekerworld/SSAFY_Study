# 2. 잘못 입력한 숫자 지우기

# 회계 프로그램에 숫자를 하나씩 입력한다.
# 숫자 0이 들어오면 "방금 입력한 숫자를 취소"한다.
# 즉, 가장 최근에 입력한 숫자를 하나 삭제한다.
#
# 모든 입력 처리가 끝난 뒤
# 남아 있는 숫자의 합을 출력하자.

# [입력 예시]
# 10
# 5
# 8
# 0
# 3
# 0
# 7

# 처리 과정
# []
# [10]
# [10, 5]
# [10, 5, 8]
# [10, 5]       <- 0이므로 8 취소
# [10, 5, 3]
# [10, 5]       <- 0이므로 3 취소
# [10, 5, 7]

# [출력 예시]
# 22

numbers = [10, 5, 8, 0, 3, 0, 7]
stack = []

for number in numbers:

    # number가 0이면 가장 최근 숫자를 제거하고,
    # 0이 아니면 스택에 추가하세요.
    None

print(sum(stack))
